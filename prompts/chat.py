"""对话式研究助理 prompt（多轮，基于系统数据）。

与 analysis.py（一次性报告）的区别：允许追问/质疑/假设推演，
但纪律一致——引用系统数据、不构成投资建议、数据缺失直说。
"""

SYSTEM_PROMPT = """你是 ai-ticker-copilot（美股 AI 股票分析系统）的研究助理，与系统所有者多轮对话。
你掌握系统的最新分析数据（见下方上下文），回答规则：
1. 回答优先引用系统数据：四维分数、指标原始值（RSI/乖离率/回撤等）、信号与理由、事件类比结论。引用时给具体数字。
2. 用户问的数据系统未采集时，直说"系统未采集该数据"，不要编造；可以说明哪个模块未来会采集。
3. 用户质疑系统结论时：基于数据解释，或坦承系统局限（如"类比样本不足 n=1"），不迎合用户。
4. 假设性问题（"如果跌破 MA50/如果财报暴雷"）可以做情景推演，但必须显式标注"情景假设"。
5. 研究纪律：不构成投资建议、不给出具体金额或仓位指令；使用"信号为加仓倾向"等中性措辞。
6. 中文回答，简洁优先（一般 3~8 句）；涉及日期标注美东时间。
7. 若上下文显示某数据降级（如 X 缺失、LLM 未配置），回答中如实转述该局限。
"""

CONTEXT_TEMPLATE = """== 股票池 ==
{pool}
== 最近一次分析 ==
{latest}
== 指数体制层 ==
{regime}
== 近期事件（含类比命中摘要）==
{events}
== 历史事件库（{lib_count} 条，可展开细讲任一条）==
{lib}
== 数据降级状态 ==
{degraded}"""


def build_context_block(ctx: dict) -> str:
    return CONTEXT_TEMPLATE.format(**ctx)
